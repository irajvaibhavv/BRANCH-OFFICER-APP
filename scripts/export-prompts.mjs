// Index just past the template literal opening at `i`, honouring ${ } with nested strings and templates.
function skipTemplate(s, i) {
  for (let j = i + 1; j < s.length; j++) {
    if (s[j] === '\\') j++;
    else if (s[j] === '`') return j + 1;
    else if (s[j] === '$' && s[j + 1] === '{') j = skipExpr(s, j + 2) - 1;
  }
  throw new Error('unterminated template');
}

function skipExpr(s, i) {
  for (let depth = 1, j = i; j < s.length; j++) {
    const c = s[j];
    if (c === '`') j = skipTemplate(s, j) - 1;
    else if (c === "'" || c === '"') { j++; while (s[j] !== c) j += s[j] === '\\' ? 2 : 1; }
    else if (c === '{') depth++;
    else if (c === '}' && --depth === 0) return j + 1;
  }
  throw new Error('unterminated expression');
}

function extract(file, anchor, kind) {
  const src = readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
  const at = src.indexOf(anchor);
  if (at < 0) throw new Error(`${file}: anchor not found: ${anchor}`);
  if (kind === 'function') return src.slice(at, src.indexOf('\n}\n', at) + 2);
  if (kind === 'quote') {
    const open = src.indexOf("'", at);
    return src.slice(open + 1, src.indexOf("',", open));
  }
  const open = src.indexOf('`', at);
  return src.slice(open + 1, skipTemplate(src, open) - 1);
}

